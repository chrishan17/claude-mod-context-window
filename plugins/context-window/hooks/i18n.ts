const DICTIONARIES: Record<Lang, Dictionary> = { zh, en }

/** Whether a key has a translation (an attachment name the engine may add later has none). */
export function hasKey(key: string): boolean {
  return key in zh
}

/** The string for `key` in `lang`, `{0}`, `{1}` filled from `args`; the key itself when unknown. */
export function t(lang: Lang, key: string, ...args: readonly (string | number)[]): string {
  const text = DICTIONARIES[lang][key] ?? zh[key] ?? key

  return text.replace(/\{(\d)\}/g, (_, index: string) => String(args[Number(index)] ?? ''))
}

/**
 * The language to draw in: the plugin's `language` option, or with `auto`
 * Claude Code's own `language` setting, then the system locale.
 */
export function pickLang(option: string | undefined, setting: string | undefined, locale: string | undefined): Lang {
  if (option === 'zh' || option === 'en') return option
  const said = `${setting ?? ''}`.toLowerCase()
  if (said) return /zh|chinese|中文|mandarin/.test(said) ? 'zh' : 'en'

  return /^zh/i.test(locale ?? '') ? 'zh' : 'en'
}
